fn glyph(c: char) -> [u8; 7] {
    let c = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .map(|(_, b)| *b)
        .unwrap_or([0b11111, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11111])
}

/// Width in pixels of `text` at `scale` (5 px glyph + 1 px gap per char).
pub fn text_width(text: &str, scale: usize) -> usize {
    let n = text.chars().count();
    if n == 0 {
        0
    } else {
        (n * 6 - 1) * scale
    }
}

/// Draw `text` into an RGB888 canvas of width `w` at (x, y).
pub fn draw_text(canvas: &mut [u8], w: usize, x: usize, y: usize, text: &str, scale: usize, rgb: [u8; 3]) {
    let h = canvas.len() / 3 / w;
    for (i, c) in text.chars().enumerate() {
        let g = glyph(c);
        let gx = x + i * 6 * scale;
        for (row, bits) in g.iter().enumerate() {
            for col in 0..5 {
                if bits & (0b10000 >> col) == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let px = gx + col * scale + dx;
                        let py = y + row * scale + dy;
                        if px < w && py < h {
                            let o = (py * w + px) * 3;
                            canvas[o..o + 3].copy_from_slice(&rgb);
                        }
                    }
                }
            }
        }
    }
}

/// Draw `text` horizontally centred on row `y`.
pub fn draw_centered(canvas: &mut [u8], w: usize, y: usize, text: &str, scale: usize, rgb: [u8; 3]) {
    let tw = text_width(text, scale);
    let x = w.saturating_sub(tw) / 2;
    draw_text(canvas, w, x, y, text, scale, rgb);
}
